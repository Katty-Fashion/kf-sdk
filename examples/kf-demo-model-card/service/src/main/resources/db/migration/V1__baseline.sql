-- =============================================================================
-- V1 -- the OWN database of kf-demo-model-card (quick 261102-module-tutorial, sdk-protocol.md §3.3)
--
-- The database lives in the module's compose (service `db`, without kf.expose, so off the platform network): the
-- platform never reaches it, never reads it and never runs DDL in it. Its migrations are the module's own Flyway.
-- Tenant isolation inside it is the MODULE's obligation, on the tenant of the verified signed context (§9.2).
--
-- WHO RUNS WHAT (the pattern of kf-feedback)
--   Flyway runs as the database owner (POSTGRES_USER of `db`, its password in the volume db-credentials). The
--   application connects as kfdemocard_app, created here: NOT the owner of any table, NOSUPERUSER, NOBYPASSRLS, only
--   DML. Its password comes from the same volume through the Flyway placeholder app_password.
--
-- TENANT ISOLATION
--   model_pin has ROW LEVEL SECURITY, FORCEd (the owner too), on the GUC kfdemocard.tenant, set by the application with
--   set_config('kfdemocard.tenant', <the context's tenant>, true) as the first statement of each transaction
--   (TenantScope). Unset or empty -> NULL -> no row is visible and none can be written (fail-closed).
--
-- THE TABLE
--   model_pin   one row per (tenant, model, user): the user (the OIDC subject of the verified context) pinned the
--               platform's model model_id to the cards page. model_id is a NUMBER of the platform, never a foreign key
--               (the module has no access to the platform's tables, AR-16). pinned_name keeps the model's name at the
--               last pin, for the notification when the model is deleted.
-- =============================================================================

DO $$
BEGIN
    IF length('${app_password}') NOT BETWEEN 16 AND 256 OR '${app_password}' !~ '^[A-Za-z0-9+/=_.-]+$' THEN
        RAISE EXCEPTION 'the application password (placeholder app_password) must be 16-256 characters of [A-Za-z0-9+/=_.-]';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'kfdemocard_app') THEN
        CREATE ROLE kfdemocard_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS PASSWORD '${app_password}';
    END IF;
END
$$;

CREATE TABLE model_pin (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    uuid          NOT NULL,
    model_id     bigint        NOT NULL,
    pinned_by    varchar(255)  NOT NULL,
    pinned_name  varchar(255),
    pinned_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ck_model_pin_model CHECK (model_id > 0),
    CONSTRAINT ck_model_pin_subject CHECK (btrim(pinned_by) <> ''),
    CONSTRAINT uq_model_pin UNIQUE (tenant_id, model_id, pinned_by)
);
CREATE INDEX idx_model_pin_user ON model_pin (tenant_id, pinned_by, pinned_at DESC, id DESC);
CREATE INDEX idx_model_pin_model ON model_pin (tenant_id, model_id);

ALTER TABLE model_pin ENABLE ROW LEVEL SECURITY;

CREATE POLICY model_pin_tenant_isolation ON model_pin
    USING (tenant_id = NULLIF(current_setting('kfdemocard.tenant', true), '')::uuid)
    WITH CHECK (tenant_id = NULLIF(current_setting('kfdemocard.tenant', true), '')::uuid);

ALTER TABLE model_pin FORCE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO kfdemocard_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON model_pin TO kfdemocard_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO kfdemocard_app;
